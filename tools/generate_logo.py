"""The title logo, from its source drawing (tools/art/logo_source.png):
the same letters, cleaned onto one palette so every pixel is a solid,
exact colour (near-twins merged, the half-clear shadow made solid).

Also writes the boot splash (assets/icon/splash.png, the logo at 2x) and,
for the animated title (scripts/ui/title_logo.gd):
- assets/ui/logo_heart_beat.png: the heart in THROUGH a pixel bigger all
  round, drawn over it on each beat;
- scripts/ui/logo_data.gd: where the heart, the gem and the underline
  are, and which rows are the top line.

Run: python3 tools/generate_logo.py
"""
import os

import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")

# The logo's palette: plum outlines and shadow, sand faces lit to cream,
# the rose heart and gem.
PALETTE = [
    (36, 27, 48), (54, 38, 63), (70, 40, 68), (84, 59, 83), (112, 59, 80), (118, 51, 83),
    (161, 101, 91), (161, 121, 103), (199, 150, 116), (233, 203, 149), (255, 240, 192),
    (181, 68, 109), (187, 85, 117), (241, 109, 132), (255, 180, 160),
]
HEART_TONES = {(241, 109, 132), (255, 180, 160)}
GEM_TONES = {(181, 68, 109), (187, 85, 117), (118, 51, 83)}


def nearest(c):
    return min(PALETTE, key=lambda p: sum((p[i] - c[i]) ** 2 for i in range(3)))


def clean(src):
    a = np.array(src.convert("RGBA")).astype(int)
    out = np.zeros_like(a)
    for y in range(a.shape[0]):
        for x in range(a.shape[1]):
            if a[y, x, 3] > 0:
                out[y, x] = nearest(tuple(a[y, x, :3])) + (255,)
    return Image.fromarray(out.astype(np.uint8), "RGBA")


def main():
    logo = clean(Image.open(os.path.join(HERE, "art", "logo_source.png")))
    logo.save(os.path.join(ROOT, "assets", "ui", "logo.png"))
    # The boot splash: the logo at two screen pixels to each of its own.
    logo.resize((logo.width * 2, logo.height * 2), Image.NEAREST).save(os.path.join(ROOT, "assets", "icon", "splash.png"))
    a = np.array(logo).astype(int)
    h, w = a.shape[:2]
    # The heart in THROUGH (on the top line).
    heart = [(x, y) for y in range(0, 32) for x in range(w) if tuple(a[y, x, :3]) in HEART_TONES]
    hx0, hy0 = min(p[0] for p in heart), min(p[1] for p in heart)
    hx1, hy1 = max(p[0] for p in heart), max(p[1] for p in heart)
    # Its beat: every heart pixel's neighbours become heart too, the old rim
    # rose, the new rim the outline's plum, the light spot kept.
    box = (hx0 - 2, hy0 - 2, hx1 + 3, hy1 + 3)
    region = a[box[1]:box[3], box[0]:box[2]].copy()
    inside = {(x - box[0], y - box[1]) for x, y in heart}
    grown = set(inside)
    for x, y in inside:
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            grown.add((x + dx, y + dy))
    beat = np.zeros_like(region)
    for x, y in grown:
        if 0 <= x < region.shape[1] and 0 <= y < region.shape[0]:
            beat[y, x] = region[y, x] if (x, y) in inside else (241, 109, 132, 255)
    for x, y in list(grown):
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            p = (x + dx, y + dy)
            if p not in grown and 0 <= p[0] < region.shape[1] and 0 <= p[1] < region.shape[0]:
                beat[p[1], p[0]] = (70, 40, 68, 255)
    # Brighter at the height of the beat.
    for x, y in inside:
        if tuple(beat[y, x, :3]) == (241, 109, 132):
            beat[y, x] = (255, 140, 150, 255)
    Image.fromarray(beat.astype(np.uint8), "RGBA").save(os.path.join(ROOT, "assets", "ui", "logo_heart_beat.png"))
    # The gem under HEART, and the underline running out from it.
    gem = [(x, y) for y in range(h) for x in range(w) if tuple(a[y, x, :3]) in GEM_TONES and y > 70]
    gx = (min(p[0] for p in gem) + max(p[0] for p in gem)) // 2
    gy = (min(p[1] for p in gem) + max(p[1] for p in gem)) // 2
    line_top = min(p[1] for p in gem) - 1
    # The top line ends where HEART's letters begin (the emptiest row between).
    counts = [(a[y, :, 3] > 0).sum() for y in range(h)]
    split = min(range(26, 40), key=lambda y: counts[y])
    lines = [
        "extends RefCounted",
        "## Generated by tools/generate_logo.py: where the parts of the title logo",
        "## are, in logo pixels.",
        "",
        "## Where logo_heart_beat.png is drawn over the heart in THROUGH.",
        "const HEART_AT := Vector2i(%d, %d)" % (box[0], box[1]),
        "## The gem under HEART, and the row the underline starts on.",
        "const GEM_AT := Vector2i(%d, %d)" % (gx, gy),
        "const LINE_ROW := %d" % line_top,
        "## Rows above this are the top line (HALL THROUGH).",
        "const SPLIT_ROW := %d" % split,
    ]
    with open(os.path.join(ROOT, "scripts", "ui", "logo_data.gd"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print("logo", logo.size, "heart box", box, "gem", (gx, gy), "line row", line_top, "split", split)


if __name__ == "__main__":
    main()
